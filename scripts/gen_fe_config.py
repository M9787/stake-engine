r"""Generate the frontend config.ts from the math frontend config.

Math writes library/configs/config_fe_<game>.json. The web app needs the same data as a
TypeScript literal with `symbols` as an object and `paddingReels` keyed by game type.

Usage (from stake\): math-sdk\env\Scripts\python.exe scripts\gen_fe_config.py [--game <gameId>] [--out <file>]
Default game: seventh_veil. Default output: the game's config.ts (tools/gamedef/gamectx.py).
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools", "gamedef"))
from gamectx import Game, game_arg  # noqa: E402


def render(g: Game) -> str:
    fe = g.fe()
    symbols = {}
    for entry in fe["symbols"]:
        symbols.update(entry)

    config = {
        "providerName": fe["providerName"],
        "gameName": fe["gameName"],
        "gameID": fe["gameID"],
        "rtp": fe["rtp"],
        "numReels": fe["numReels"],
        "numRows": fe["numRows"],
        "betModes": fe["betModes"],
        "symbols": symbols,
        # types.ts derives GameType from these keys.
        "paddingReels": {"basegame": "", "freegame": ""},
    }
    body = json.dumps(config, indent="\t")
    return (
        f"// Generated by scripts/gen_fe_config.py from math config_fe_{g.id}.json. Do not edit.\n"
        f"export default {body};\n"
    )


def main():
    g = Game(game_arg())
    dst = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else str(g.config_ts)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    text = render(g)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {dst}: modes {list(g.fe()['betModes'])}")


if __name__ == "__main__":
    main()
