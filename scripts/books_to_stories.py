"""Turn math books into Storybook data + stories, and check the math<->web contract.

  books_to_stories.py            write stories for base / star / tower from publish_files books
  books_to_stories.py --check    only compare book event types with bookEventHandlerMap.ts keys

Usage (from stake\\): math-sdk\\env\\Scripts\\python.exe scripts\\books_to_stories.py [--check]
Exit code 1 if any book event type has no handler.
"""

import io
import json
import os
import re
import sys

import zstandard as zstd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB = os.path.join(ROOT, "math-sdk", "games", "seventh_veil", "library", "publish_files")
APP = os.path.join(ROOT, "game", "web", "seventh-veil", "src")
HANDLERS = os.path.join(APP, "game", "bookEventHandlerMap.ts")
STORIES = os.path.join(APP, "stories")

# mode -> (bet mode key in the web app, cost in base bets)
MODES = {"base": ("BASE", 1.0), "star": ("STAR", 100.0), "tower": ("TOWER", 400.0)}
MAX_PAYOUT = 7777700  # 77,777x in lookup units
MAX_SCAN = 20000  # books scanned per mode when sampling


def iter_books(mode, limit=None):
    with open(os.path.join(PUB, f"books_{mode}.jsonl.zst"), "rb") as fh:
        reader = io.TextIOWrapper(zstd.ZstdDecompressor().stream_reader(fh), encoding="utf-8")
        for n, line in enumerate(reader):
            if limit is not None and n >= limit:
                return
            if line.strip():
                yield json.loads(line)


def handler_keys():
    src = open(HANDLERS, encoding="utf-8").read()
    return set(re.findall(r"^\t(\w+): async", src, re.MULTILINE))


def check():
    keys = handler_keys()
    seen = set()
    for mode in ("base", "omen", "prophecy", "star", "tower"):
        for book in iter_books(mode):
            seen.update(ev["type"] for ev in book["events"])
    missing = sorted(seen - keys)
    print(f"book event types: {sorted(seen)}")
    print(f"handler keys:     {sorted(keys)}")
    print(f"missing handlers: {missing}")
    return 0 if not missing else 1


def categorize(book, cost):
    pay = book["payoutMultiplier"] / 100
    types = {ev["type"] for ev in book["events"]}
    variant = next((ev["variant"] for ev in book["events"] if ev["type"] == "bonusVariant"), None)
    if book["payoutMultiplier"] >= MAX_PAYOUT:
        return "max_win"
    if variant and cost == 1.0:
        return f"bonus_{variant}"
    if pay == 0:
        return "loss"
    if pay <= cost:
        return "win_below_cost"
    if pay >= 15 * cost and "freeSpinTrigger" not in types:
        return "big_win"
    if pay >= 15 * cost:
        return "big_bonus"
    return "win"


def ts(value):
    return "export default " + json.dumps(value, indent="\t") + ";\n"


BOOK_STORY = """<script lang="ts" module>
	import {{ defineMeta }} from '@storybook/addon-svelte-csf';

	const {{ Story }} = defineMeta({{ title: 'MODE_{title}/book' }});
</script>

<script lang="ts">
	// Generated by scripts/books_to_stories.py. Do not edit.
	import {{ StoryGameTemplate, StoryLocale, type TemplateArgs, templateArgs }} from 'components-storybook';
	import {{ stateBet }} from 'state-shared';

	import Game from '../components/Game.svelte';
	import {{ setContext }} from '../game/context';
	import {{ playBet }} from '../game/utils';
	import books from './data/{mode}_books';

	setContext();

	const play = async (book: any) => {{
		stateBet.activeBetModeKey = '{key}';
		await playBet({{ ...book, state: book.events }});
	}};
</script>

{{#snippet template(args: TemplateArgs<any>)}}
	<StoryGameTemplate skipLoadingScreen={{args.skipLoadingScreen}} action={{async () => await args.action?.(args.data)}}>
		<StoryLocale lang="en">
			<Game />
		</StoryLocale>
	</StoryGameTemplate>
{{/snippet}}
{stories}"""

EVENT_STORY = """<script lang="ts" module>
	import {{ defineMeta }} from '@storybook/addon-svelte-csf';

	const {{ Story }} = defineMeta({{ title: 'MODE_{title}/bookEvent' }});
</script>

<script lang="ts">
	// Generated by scripts/books_to_stories.py. Do not edit.
	import {{ StoryGameTemplate, StoryLocale, type TemplateArgs, templateArgs }} from 'components-storybook';

	import Game from '../components/Game.svelte';
	import {{ setContext }} from '../game/context';
	import {{ playBookEvent }} from '../game/utils';
	import events from './data/{mode}_events';

	setContext();
</script>

{{#snippet template(args: TemplateArgs<any>)}}
	<StoryGameTemplate skipLoadingScreen={{args.skipLoadingScreen}} action={{async () => await args.action?.(args.data)}}>
		<StoryLocale lang="en">
			<Game />
		</StoryLocale>
	</StoryGameTemplate>
{{/snippet}}
{stories}"""


def story(name, data_expr, action):
    return f"""
<Story
	name="{name}"
	args={{templateArgs({{ skipLoadingScreen: true, data: {data_expr}, action: {action} }})}}
	{{template}}
/>
"""


def write_mode(mode, key, cost):
    samples, events = {}, {}
    for book in iter_books(mode, MAX_SCAN):
        cat = categorize(book, cost)
        if cat not in samples:
            samples[cat] = book
        for ev in book["events"]:
            events.setdefault(ev["type"], ev)
    data_dir = os.path.join(STORIES, "data")
    with open(os.path.join(data_dir, f"{mode}_books.ts"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/books_to_stories.py from math books. Do not edit.\n" + ts(samples))
    with open(os.path.join(data_dir, f"{mode}_events.ts"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/books_to_stories.py from math books. Do not edit.\n" + ts(events))

    title = mode.upper()
    name = mode.capitalize()
    book_stories = "".join(
        story(cat, f"books['{cat}']", "async (data: any) => await play(data)") for cat in sorted(samples)
    )
    event_stories = "".join(
        story(t, f"events['{t}']", "async (data: any) => await playBookEvent(data, { bookEvents: [] })")
        for t in sorted(events)
    )
    with open(os.path.join(STORIES, f"Mode{name}Book.stories.svelte"), "w", encoding="utf-8", newline="\n") as f:
        f.write(BOOK_STORY.format(title=title, mode=mode, key=key, stories=book_stories))
    with open(os.path.join(STORIES, f"Mode{name}BookEvent.stories.svelte"), "w", encoding="utf-8", newline="\n") as f:
        f.write(EVENT_STORY.format(title=title, mode=mode, stories=event_stories))
    print(f"{mode}: book stories {sorted(samples)}; event stories {len(events)}")


def main():
    if "--check" in sys.argv:
        sys.exit(check())
    # Remove the cluster sample stories/data this app was forked from.
    for old in ("ModeBonusBook.stories.svelte", "ModeBonusBookEvent.stories.svelte",
                "data/bonus_books.ts", "data/bonus_events.ts"):
        path = os.path.join(STORIES, old)
        if os.path.exists(path):
            os.remove(path)
    for mode, (key, cost) in MODES.items():
        write_mode(mode, key, cost)
    sys.exit(check())


if __name__ == "__main__":
    main()
