r"""Write build/<id>/web/skin.generated.ts: the skin data the core web app imports through $skin (M10).

Usage:  math-sdk\env\Scripts\python.exe tools\gen\gen_skin_ts.py [--game <gameId>] [--out <file>]
Holds identity, board, symbol roster and the generated rules (gen_rules.py). Data only, no code.
"""

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "gamedef"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamectx import Game, game_arg  # noqa: E402
from gen_rules import build as build_rules  # noqa: E402


def render(g: Game) -> str:
    gd = g.gdef
    rules = build_rules(g, "en")
    skin = {
        "gameId": g.id,
        "displayName": gd["identity"]["displayName"],
        "version": gd["identity"]["version"],
        "board": {"reels": gd["board"]["reels"], "rows": gd["board"]["rows"]},
        "symbols": [{k: s[k] for k in ("id", "role", "tier") if k in s} for s in gd["symbols"]],
        "bonusVariants": [v["id"] for v in gd["features"]["bonusVariants"]],
        "gridCap": gd["features"]["gridMultiplier"]["cap"],
        "theme": gd.get("theme", {}),
        "presentation": gd.get("presentation", {}),
        "rules": {k: rules[k] for k in ("texts", "paytable", "modes")},
    }
    body = json.dumps(skin, indent="\t", ensure_ascii=False)
    return (
        f"// Generated by tools/gen/gen_skin_ts.py from skins/{g.skin.name}. Do not edit: edit the skin, then regenerate.\n"
        f"const skin = {body} as const;\n\nexport default skin;\n"
    )


def main():
    g = Game(game_arg())
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else g.gen_web / "skin.generated.ts"
    os.makedirs(out.parent, exist_ok=True)
    out.write_text(render(g), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
