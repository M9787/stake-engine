r"""Write build\<id>\web\assets.generated.ts: which asset slots the skin has filled (docs/10 plan v3.3, 10.6a).

Usage:  math-sdk\env\Scripts\python.exe tools\gen\gen_assets_ts.py --game <gameId> [--check]

The core app renders every image slot through SlotVisual: the skin's file when the slot is filled
(skins\<skin>\assets.lock.json, written by tools\assets\ingest.py), else the slot's procedural fallback.
Paths are relative to the static root (gen_web_static.py copies skins\<skin>\assets\ there) and never
contain "..". Data only.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "assets"))
from catalog import Catalog  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "gamedef"))
from gamectx import game_arg  # noqa: E402


def build(cat: Catalog) -> dict:
    lock_path = cat.game.skin / "assets.lock.json"
    lock = json.loads(lock_path.read_text(encoding="utf-8")).get("slots", {}) if lock_path.exists() else {}
    symbols = {s["id"]: s for s in cat.game.gdef["symbols"]}
    slots = {}
    for s in cat.slots:
        if s["kind"] not in ("image", "font") or s.get("ship") == "tile" or s["required"] == "source":
            continue
        rec = lock.get(s["id"])
        file = None
        if rec and rec["file"].startswith("assets/"):
            file = rec["file"][len("assets/"):]
            if ".." in file:
                raise SystemExit(f"{s['id']}: asset path may not contain '..': {file}")
        entry = {"kind": s["kind"], "file": file, "fallback": s.get("fallback"), "motion": s.get("motion")}
        if s.get("px"):
            entry["px"] = s["px"]
        sym = symbols.get(s["id"].removeprefix("symbol.")) if s["id"].startswith("symbol.") else None
        if sym:
            entry["tier"] = sym.get("tier", sym["role"])
        slots[s["id"]] = entry
    palette = list(cat.game.gdef.get("theme", {}).get("palette", {}).values())
    return {"palette": palette, "slots": dict(sorted(slots.items()))}


def render(cat: Catalog) -> str:
    body = json.dumps(build(cat), indent="\t", ensure_ascii=False)
    return (f"// Generated by tools/gen/gen_assets_ts.py from skins/{cat.game.skin.name}. Do not edit.\n"
            f"const assets = {body} as const;\n\nexport default assets;\n")


def main():
    cat = Catalog(game_arg())
    out = cat.game.gen_web / "assets.generated.ts"
    text = render(cat)
    if "--check" in sys.argv:
        ok = out.exists() and out.read_text(encoding="utf-8") == text
        print(f"{'OK' if ok else 'STALE'}: {out}")
        sys.exit(0 if ok else 1)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    filled = sum(1 for v in build(cat)["slots"].values() if v["file"])
    print(f"wrote {out} ({filled} filled slots)")


if __name__ == "__main__":
    main()
