r"""Write the thin math-sdk game folder (shim) for every skin, and install the core.

Usage:  math-sdk\\env\\Scripts\\python.exe tools\\gen\\gen_shim.py [--game <gameId>]
Called by scripts\\sync.ps1. One direction only: core\\ and skins\\ are the source of truth.

- core/math/cluster_tumble/*.py  -> math-sdk/games/core_cluster_tumble/  (mirror, .py only)
- per skin (identity.gameId):    -> math-sdk/games/<gameId>/
    game_config.py  GameConfig = build("<gameId>")   (rgs_verification imports games.<id>.game_config)
    run.py          run_core.main("<gameId>", GameConfig)
    reels/*.csv     copied from skins/<skin>/math/reels
  Other .py files in the game folder (an older hand-written copy) are removed; library/ is kept.
Why a shim: math-sdk resolves games.<game_id> by folder name (output_filenames.py,
rgs_verification.py), and SDK games 0_0_* stay untouched (docs/10 section 1).
"""

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE_SRC = ROOT / "core" / "math" / "cluster_tumble"
GAMES = ROOT / "math-sdk" / "games"
CORE_DST = GAMES / "core_cluster_tumble"

GAME_CONFIG = '''"""Generated by tools/gen/gen_shim.py from {skin}/game.json. Do not edit: edit the skin, then sync."""

from games.core_cluster_tumble.config_builder import build

GameConfig = build("{game_id}")
'''

RUN = '''"""Generated by tools/gen/gen_shim.py. Do not edit. Run from math-sdk: python games/{game_id}/run.py"""

from games.core_cluster_tumble.run_core import main
from games.{game_id}.game_config import GameConfig

if __name__ == "__main__":
    main("{game_id}", GameConfig)
'''

SHIM_FILES = {"game_config.py", "run.py"}


def write_if_changed(path: Path, text: str):
    """Byte-exact: LF endings as in the source, so the install equals core/ byte for byte."""
    data = text.replace("\r\n", "\n").encode("utf-8")
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)
        return True
    return False


def install_core():
    CORE_DST.mkdir(parents=True, exist_ok=True)
    wanted = {p.name for p in CORE_SRC.glob("*.py")}
    for stale in CORE_DST.glob("*.py"):
        if stale.name not in wanted:
            stale.unlink()
    changed = 0
    for n in sorted(wanted):  # verbatim byte copy: the install equals core/ byte for byte
        data, dst = (CORE_SRC / n).read_bytes(), CORE_DST / n
        if not dst.exists() or dst.read_bytes() != data:
            dst.write_bytes(data)
            changed += 1
    print(f"ok    core/math/cluster_tumble -> math-sdk/games/core_cluster_tumble ({len(wanted)} files, {changed} changed)")


def install_shim(skin_dir: Path):
    gdef = json.loads((skin_dir / "game.json").read_text(encoding="utf-8"))
    game_id = gdef["identity"]["gameId"]
    dst = GAMES / game_id
    dst.mkdir(parents=True, exist_ok=True)
    for stale in dst.glob("*.py"):
        if stale.name not in SHIM_FILES:
            stale.unlink()
    pycache = dst / "__pycache__"
    if pycache.exists():
        shutil.rmtree(pycache)
    for extra in ("readme.txt",):
        if (dst / extra).exists():
            (dst / extra).unlink()
    write_if_changed(dst / "game_config.py", GAME_CONFIG.format(skin=f"skins/{skin_dir.name}", game_id=game_id))
    write_if_changed(dst / "run.py", RUN.format(game_id=game_id))
    reels_src, reels_dst = skin_dir / "math" / "reels", dst / "reels"
    reels_dst.mkdir(exist_ok=True)
    wanted = {p.name for p in reels_src.glob("*.csv")}
    for stale in reels_dst.glob("*"):
        if stale.name not in wanted:
            stale.unlink()
    for name in wanted:
        shutil.copyfile(reels_src / name, reels_dst / name)
    print(f"ok    skins/{skin_dir.name} -> math-sdk/games/{game_id} (shim, {len(wanted)} reel strips)")


def main():
    only = sys.argv[sys.argv.index("--game") + 1] if "--game" in sys.argv else None
    install_core()
    for game_json in sorted((ROOT / "skins").glob("*/game.json")):
        gid = json.loads(game_json.read_text(encoding="utf-8"))["identity"]["gameId"]
        if only is None or only == gid:
            install_shim(game_json.parent)


if __name__ == "__main__":
    main()
