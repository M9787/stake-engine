"""Generate the frontend config.ts from the math frontend config.

Math writes library/configs/config_fe_<game>.json. The web app needs the same data as a
TypeScript literal with `symbols` as an object and `paddingReels` keyed by game type.

Usage (from stake\\): math-sdk\\env\\Scripts\\python.exe scripts\\gen_fe_config.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "math-sdk", "games", "seventh_veil", "library", "configs", "config_fe_seventh_veil.json")
DST = os.path.join(ROOT, "game", "web", "seventh-veil", "src", "game", "config.ts")


def main():
    with open(SRC, encoding="utf-8") as f:
        fe = json.load(f)

    symbols = {}
    for entry in fe["symbols"]:
        symbols.update(entry)

    config = {
        "providerName": fe["providerName"],
        "gameName": fe["gameName"],
        "gameID": fe["gameID"],
        "rtp": fe["rtp"],
        "numReels": fe["numReels"],
        "numRows": fe["numRows"],
        "betModes": fe["betModes"],
        "symbols": symbols,
        # types.ts derives GameType from these keys.
        "paddingReels": {"basegame": "", "freegame": ""},
    }
    body = json.dumps(config, indent="\t")
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen_fe_config.py from math config_fe_seventh_veil.json. Do not edit.\n")
        f.write(f"export default {body};\n")
    print(f"wrote {DST}: {len(symbols)} symbols, modes {list(fe['betModes'])}")


if __name__ == "__main__":
    main()
